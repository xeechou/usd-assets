#!/usr/bin/env python
'''
Helper Script to generate an aggregated scene from all the files generated by
authorUSDfilesforSubset.py (as specified by fileFilter)
Each usda file is added as a sub-layer of the aggregated scene.
All files specify the same geometry but different materials.
The geometry will be one after the composition, and will be instanced N times
and assigned different materials.
'''

from pxr import Usd, UsdGeom, UsdShade
import glob, math
from pathlib import Path

# Wildcards filter for the files to load
fileFilter = 'Prism_*.usda'

# instancesMax = 0 will generate as many instances as the available materials
# setting it to any other number will generate that exact amount of instances
# if the instances are more than the available materials the materials will repeat
instancesMax = 0

# Offset shift the block of instances away from the origin (where the original object is)
# Note that Z is negative Z, so a positive offset will move the grid forward
offsetX = 2000.0
offsetZ = 0.0

# separation is the distance in X and Z of each instance in the grid
separation = 1000.0

# Set to True to hide the original object
hideOriginal = True

# Set to True to center the block of instances grid to 0,0
# The offset values above will be overwritten in this case
centerGrid = True

def main():

    global instancesMax, offsetX, offsetZ

    # Path to source files
    path = "./"

    PRISM_PRESETS = [i for i in glob.glob(path + fileFilter)]
    print("Files Count: ", len(PRISM_PRESETS))

    stage = Usd.Stage.CreateNew('aggregatescene.usda')

    UsdGeom.SetStageUpAxis(stage, UsdGeom.Tokens.y)
    UsdGeom.SetStageMetersPerUnit(stage, 0.01)

    # Add all sub-layers for all files found
    # This might generate an awful lot of warning messages. Ignore.
    for preset in PRISM_PRESETS:
        stage.GetRootLayer().subLayerPaths.append(preset)

    # Get the list of materials collected
    matsPrim = stage.GetPrimAtPath('/MaterialX/Materials')
    MATS_LIST = matsPrim.GetAllChildren()
    matsNum = len(MATS_LIST)
    print("Materials Count: ", matsNum)

    # Adjust number of instances
    if instancesMax == 0:
        instancesMax = matsNum
    colMax = int(math.sqrt(instancesMax))

    # Adjust offset if auto center enabled
    if centerGrid:
        offsetX = -colMax/2.0*separation + separation/2.0
        offsetZ = colMax/2.0*separation - separation/2.0

    # Creates the instances and assign materials
    col = 0
    row = 0
    matNum = 0
    for instNum in range(0, instancesMax):
        matNum = int(math.fmod(instNum, matsNum))
        mat = MATS_LIST[matNum]
        refPath = '/objSballRef_' + mat.GetName() + '_' + str(instNum)

        refShaderBall = UsdGeom.Xform.Define(stage, refPath).GetPrim()
        refShaderBall.GetReferences().AddInternalReference('/TestMaterial/Scenes/scene')

        UsdGeom.XformCommonAPI(refShaderBall).SetTranslate((col*separation+offsetX, 0.0, -row*separation+offsetZ))

        refMesh = stage.OverridePrim(refPath + '/Preview_Mesh/submesh')
        material_binding_api = UsdShade.MaterialBindingAPI.Apply(refMesh)
        mat1 = UsdShade.Material.Get(stage, mat.GetPath())
        material_binding_api.Bind(mat1)

        col += 1
        if col >= colMax:
            col = 0
            row += 1

    # Add a camera
    # We won't modify the existing /Camera which still looks at the original object
    camXformPath = '/CameraAll'
    camPath = '/CameraAll/CameraAll'
    camXform = UsdGeom.Xform.Define(stage, camXformPath)
    camera = UsdGeom.Camera.Define(stage, camPath)
    #camera.CreateProjectionAttr().Set(UsdGeom.Tokens.perspective)
    camera.CreateFocalLengthAttr().Set(24)
    camera.CreateHorizontalApertureAttr().Set(36)
    camera.CreateVerticalApertureAttr().Set(24)
    #camera.CreateClippingRangeAttr().Set((0.1,100000))
    #camera.CreateFocusDistanceAttr().Set(6000)

    # adjust the camera position that was set for a 5x5 grid
    # Simple scaling, not perfect, but good enough
    camTransform = UsdGeom.XformCommonAPI(camXform)
    origPos = (5900.0, 6300.0, 3300.0)
    fact = math.sqrt(colMax*colMax/2.0)/math.sqrt(5*5/2.0)
    newPos = (origPos[0]*fact + offsetX, origPos[1]*fact, origPos[2]*fact + offsetZ)
    camTransform.SetTranslate(newPos)
    camTransform.SetRotate((-43.5, 37.3, 0), UsdGeom.XformCommonAPI.RotationOrderXYZ)
    camera.CreateFocusDistanceAttr().Set(6000*fact)

    # Hide original object
    # Note that the visibility flag is set to the parent of the instanced prim
    # to avoid hiding all instances
    if hideOriginal:
        testPrim = stage.OverridePrim('/TestMaterial/Scenes')
        visAttrib = testPrim.GetAttribute("visibility")
        visAttrib.Set("invisible")

    stage.GetRootLayer().Save()

if __name__ == '__main__':
    main()
